    private void jButtonProcessActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonProcessActionPerformed
        // TODO add your handling code here:
        try
        {
            //Declaring the variables
            String product = jComboBoxProduct.getSelectedItem().toString();
            String customerName = txtName.getText();
            double price = Double.parseDouble(txtPrice.getText());
            
           //Calculating the total sales amount
            double vat = price * 0.15;
            double commission = price * 0.05;
            double total = price + vat + commission;
            
            
            //Get the process output into message dialog
            JOptionPane.showMessageDialog(this, 
                        "\nCustomer Name : " + customerName +
                        "\nPRODUCT : " + product +
                        "\nVAT : " + vat +
                        "\nCOMMISSION : " + commission +
                        "\nTOTAL : R " + total);
                    
        }catch(NumberFormatException e)
        {
            JOptionPane.showMessageDialog(this, 
                    "Please enter a valid numerical number");
        }
    }//GEN-LAST:event_jButtonProcessActionPerformed

    private void jProcessActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jProcessActionPerformed
        // TODO add your handling code here:
         try
        {
            //Declaring the variables
            String product = jComboBoxProduct.getSelectedItem().toString();
            String customerName = txtName.getText();
            double price = Double.parseDouble(txtPrice.getText());
            
           //Calculating the total sales amount
            double vat = price * 0.15;
            double commission = price * 0.05;
            double total = price + vat + commission;
            
            
            //Get the process output into message dialog
            JOptionPane.showMessageDialog(this, 
                        "\nCustomer Name : " + customerName +
                        "\nPRODUCT : " + product +
                        "\nVAT : " + vat +
                        "\nCOMMISSION : " + commission +
                        "\nTOTAL : R " + total);
                    
        }catch(NumberFormatException e)
        {
            JOptionPane.showMessageDialog(this, 
                    "Please enter a valid numerical number");
        }
              
         
          try{
              FileWriter writer = new FileWriter("data.txt");
              writer.write("DATA LOG");
              writer.write("*****************************");
              writer.write(txtName.getText());
              writer.write((String) jComboBoxProduct.getSelectedItem());
              writer.write("*****************************");
              
          }catch (IOException ex){
              JOptionPane.showMessageDialog(this,
                      "Data could not be saved to data.txt" + ex.getMessage());
          }
              
    }//GEN-LAST:event_jProcessActionPerformed

